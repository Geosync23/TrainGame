LINE_H = 7
BASE = 5   # rows above the baseline


def glyphs():
    """Returns {char: (img RGBA uint8 of size 7 x w, advance)}."""
    out = {}
    for ch, rows in list(CAPS.items()) + list(LOWER.items()):
        if len(rows) == 5: rows = rows + ['0' * len(rows[0])] * 2
        w = max(len(r) for r in rows)
        img = np.zeros((LINE_H, w, 4), np.uint8)
        for r, line in enumerate(rows):
            for c, v in enumerate(line):
                if v == '1':
                    img[r, c] = (255, 255, 255, 255)
        out[ch] = (img, w + 1)
    return out


def text_image(s, colour=(255, 255, 255, 255)):
    """Render a string with the font (for previews and the test scene)."""
    g = glyphs()
    w = sum(g[c][1] for c in s if c in g)
    img = np.zeros((LINE_H, max(w, 1), 4), np.uint8)
    x = 0
    for c in s:
        if c not in g: continue
        gi, adv = g[c]
        m = gi[..., 3] > 0
        sub = img[:, x:x + gi.shape[1]]
        sub[m] = colour
        x += adv
    return img
